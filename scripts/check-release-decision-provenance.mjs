import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { baseline } from './production-regression-baseline.mjs';
import { evaluateRelease } from './production-release-decision.mjs';
const root=process.cwd();
const sha256=v=>crypto.createHash('sha256').update(v).digest('hex');
const lock=fs.readFileSync(path.join(root,'package-lock.json'));
const dir=path.join(root,'supabase/migrations');
const migrations=fs.readdirSync(dir).filter(f=>f.endsWith('.sql')).sort();
const dependencyFingerprint=sha256(lock);
const migrationsFingerprint=sha256(migrations.map(f=>`${f}\n${fs.readFileSync(path.join(dir,f))}`).join('\n'));
const sourceSha=process.env.GITHUB_SHA;
if(process.env.CI&&!sourceSha) throw new Error('Release decision provenance requires GITHUB_SHA in CI');
const good=Object.fromEntries(Object.entries(baseline).map(([id,b])=>[id,{expected:b.expected,stages:b.stages}]));
const decision=evaluateRelease(good);
if(decision.release!=='approved') throw new Error('Known-good regression baseline must be approved');
if(!sourceSha&&!process.env.CI) console.warn('LOCAL: GITHUB_SHA unavailable');
const first=Object.keys(good)[0];
const blocked={...good,[first]:{expected:'broken',stages:[]}};
if(evaluateRelease(blocked).release!=='blocked') throw new Error('Release decision is not fail-closed');
console.log(JSON.stringify({contract:'release-decision-provenance',decision:decision.release,sourceSha:sourceSha||'local',dependencyFingerprint,migrationsFingerprint,scenarioCount:decision.scenarioCount}));
