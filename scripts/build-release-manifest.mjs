import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { verifyCanonicalManifest } from './check-canonical-certification-migrations.mjs';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p));
const sha256=x=>crypto.createHash('sha256').update(x).digest('hex');
const pkg=JSON.parse(read('package.json')); const lock=read('package-lock.json');
const canonical=verifyCanonicalManifest(path.join(root,'docs/CANONICAL_CERTIFICATION_MIGRATIONS.json'));
const manifest={schemaVersion:1,sourceSha:process.env.GITHUB_SHA||'local',packageVersion:pkg.version,dependencyFingerprint:sha256(lock),migrationFingerprint:canonical.fingerprint,migrationAnchorCommit:canonical.anchorCommit,migrationAnchorTreeSha:canonical.anchorTreeSha,generatedAt:new Date().toISOString()};
fs.writeFileSync(path.join(root,'release-manifest.json'),JSON.stringify(manifest,null,2)+'\n'); console.log(JSON.stringify(manifest));
