import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const candidates=['scripts/check-dr-recovery-contract.mjs','scripts/check-dr-recovery-readiness.mjs','scripts/check-production-recovery-gate.mjs','scripts/check-resumability-deadletter-contract.mjs','scripts/check-phase10-backup-restore-contract.mjs'];
const existing=candidates.filter(f=>fs.existsSync(path.join(root,f)));
if(existing.length<3) throw new Error(`Recovery contract incomplete: found ${existing.length}/${candidates.length}`);
const text=existing.map(f=>fs.readFileSync(path.join(root,f),'utf8').toLowerCase()).join('\n');
for(const token of ['backup','restore','rollback']) if(!text.includes(token)) throw new Error(`Recovery contract missing: ${token}`);
assert.ok(text.includes('rpo')||text.includes('rto'),'Recovery contract must define recovery objectives');
assert.ok(text.includes('fail')||text.includes('assert'),'Recovery contract must fail closed on invalid evidence');
console.log(`RECOVERY CONTRACT: PASS (${existing.length} checks)`);